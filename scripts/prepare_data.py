"""Rebuild browser data from the retained UCI Auto MPG snapshot (stdlib only)."""
import hashlib
import json
import shlex
from collections import Counter
from pathlib import Path
from statistics import mean, median, correlation

ROOT = Path(__file__).resolve().parents[1]
source = ROOT / 'data' / 'auto-mpg.data'
raw = [shlex.split(line) for line in source.read_text(encoding='utf-8').splitlines() if line.strip()]
clean, excluded = [], []
for index, values in enumerate(raw):
    mpg,cylinders,displacement,hp,weight,acceleration,year,origin,name = values
    if hp == '?':
        excluded.append({'source_row': index + 1, 'name': name, 'missing': ['Horsepower']})
        continue
    clean.append({
        'id': index + 1, 'name': name, 'year': 1900 + int(year),
        'origin': {'1':'USA','2':'Europe','3':'Japan'}[origin], 'horsepower': float(hp),
        'mpg': float(mpg), 'weight': float(weight),
        'cylinders': int(cylinders), 'acceleration': float(acceleration)
    })
meta = {
    'download_date': '2026-11-14',
    'direct_source': 'https://archive.ics.uci.edu/static/public/9/auto+mpg.zip',
    'source_page': 'https://archive.ics.uci.edu/dataset/9/auto+mpg',
    'original_dataset': 'https://archive.ics.uci.edu/dataset/9/auto+mpg',
    'original_citation': 'Quinlan, R. (1993). Auto MPG [Dataset]. UCI Machine Learning Repository. https://doi.org/10.24432/C5859H',
    'source_sha256': hashlib.sha256(source.read_bytes()).hexdigest(),
    'raw_count': len(raw), 'clean_count': len(clean), 'excluded_count': len(excluded),
    'missing_by_field': dict(Counter(field for row in excluded for field in row['missing'])),
    'years': [min(row['year'] for row in clean), max(row['year'] for row in clean)],
    'origins': dict(Counter(row['origin'] for row in clean)),
    'mean_mpg': mean(row['mpg'] for row in clean),
    'median_mpg': median(row['mpg'] for row in clean),
    'correlation_hp_mpg': correlation([row['horsepower'] for row in clean], [row['mpg'] for row in clean]),
    'year_median_mpg': {str(year): median(row['mpg'] for row in clean if row['year'] == year) for year in sorted(set(row['year'] for row in clean))},
    'origin_stats': {origin: {'n': sum(row['origin'] == origin for row in clean), 'median_mpg': median(row['mpg'] for row in clean if row['origin'] == origin)} for origin in ('USA','Europe','Japan')},
    'excluded_rows': excluded
}
(ROOT / 'data' / 'cars.json').write_text(json.dumps(clean, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
(ROOT / 'data' / 'provenance.json').write_text(json.dumps(meta, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
(ROOT / 'data' / 'cars.js').write_text('// Generated by scripts/prepare_data.py. No network request required.\nwindow.AUTO_DATA = ' + json.dumps(clean, ensure_ascii=False, separators=(',', ':')) + ';\nwindow.AUTO_META = ' + json.dumps({k:v for k,v in meta.items() if k != 'excluded_rows'}, ensure_ascii=False) + ';\n', encoding='utf-8')
print(json.dumps({k:v for k,v in meta.items() if k != 'excluded_rows'}, ensure_ascii=False, indent=2))
